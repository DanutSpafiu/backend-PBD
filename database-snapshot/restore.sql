  CREATE OR REPLACE EDITIONABLE FUNCTION "LEFT_TO_PAY" (
	 p_cnp IN clienti.cnp%TYPE,
	 p_product IN achizitii.produs%TYPE
) RETURN NUMBER AS
    v_client_id clienti.id%TYPE;
    v_count NUMBER;
    v_remaining NUMBER;
BEGIN
    IF p_cnp IS NULL OR TRIM(p_product) IS NULL THEN
	      RAISE_APPLICATION_ERROR(-20004, 'CNP and product are required');
    END IF;
	 SELECT id INTO v_client_id FROM clienti WHERE cnp = p_cnp;
	 SELECT COUNT(*), SUM(pret - suma_incasata) INTO v_count, v_remaining
    FROM achizitii WHERE client_id = v_client_id AND produs = p_product;
    IF v_count = 0 THEN
	  RAISE_APPLICATION_ERROR(-20007, 'Product not purchased by client');
    END IF;
	RETURN v_remaining;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
	     RAISE_APPLICATION_ERROR(-20003, 'Client not found');
END;
/


  CREATE OR REPLACE EDITIONABLE PROCEDURE "SELL_PRODUCT" (
    p_cnp IN clienti.cnp%TYPE,
    p_product IN achizitii.produs%TYPE,
    p_date IN achizitii.data_achizitie%TYPE,
    p_price IN achizitii.pret%TYPE,
	 p_collected IN achizitii.suma_incasata%TYPE
) AS
	v_client_id clienti.id%TYPE;
BEGIN
	 IF p_cnp IS NULL OR NOT REGEXP_LIKE(p_cnp, '^[0-9]{13}$') THEN
	 RAISE_APPLICATION_ERROR(-20004, 'CNP must contain 13 digits');
    END IF;
	  IF TRIM(p_product) IS NULL OR LENGTH(p_product) > 255 OR p_date IS NULL THEN
	RAISE_APPLICATION_ERROR(-20005, 'Product and acquisition date are required');
    END IF;
	IF p_price IS NULL OR p_price <= 0 OR p_price <> ROUND(p_price, 2)
	   OR p_collected IS NULL OR p_collected < 0 OR p_collected <> ROUND(p_collected, 2) THEN
	   RAISE_APPLICATION_ERROR(-20006, 'Invalid price or collected amount');
    END IF;
    SELECT id INTO v_client_id FROM clienti WHERE cnp = p_cnp;
    INSERT INTO achizitii(client_id, produs, data_achizitie, pret, suma_incasata)
    VALUES (v_client_id, p_product, TRUNC(p_date), p_price, p_collected);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
	     RAISE_APPLICATION_ERROR(-20003, 'Client not found');
END;
/


  CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_ACQUISITION_PAYMENT" 
BEFORE INSERT ON achizitii
FOR EACH ROW
DECLARE
	 v_available clienti.disponibil%TYPE;
    v_total NUMBER;
BEGIN
    IF :NEW.pret IS NULL OR :NEW.pret <= 0 THEN
	    RAISE_APPLICATION_ERROR(-20001, 'Price must be greater than zero');
    END IF;

    IF :NEW.suma_incasata IS NULL OR :NEW.suma_incasata < 0 THEN
	  RAISE_APPLICATION_ERROR(-20002, 'Collected amount must be non-negative');
	 END IF;

	SELECT disponibil INTO v_available
	FROM clienti
	  WHERE id = :NEW.client_id
	 FOR UPDATE;

    v_total := v_available + :NEW.suma_incasata;
    :NEW.suma_incasata := LEAST(v_total, :NEW.pret);

    UPDATE clienti
	  SET disponibil = v_total - :NEW.suma_incasata
    WHERE id = :NEW.client_id;
EXCEPTION
	WHEN NO_DATA_FOUND THEN
	 RAISE_APPLICATION_ERROR(-20003, 'Client not found');
END;
/
ALTER TRIGGER "TRG_ACQUISITION_PAYMENT" ENABLE;

